#!/usr/bin/env python3
"""Generate src/fonts.rs: 4-bit anti-aliased bitmap fonts for the UI skins.

Usage: gen_fonts.py ../src/fonts.rs --font-dir DIR

DIR must contain these OFL-licensed fonts (all available from Google Fonts,
DejaVu from dejavu-fonts.github.io):

    NunitoSans.ttf, NunitoSans-Italic.ttf     (variable fonts)
    Archivo-Regular.ttf, Archivo-Bold.ttf
    WorkSans-Regular.ttf, WorkSans-Bold.ttf
    DejaVuSansMono.ttf, DejaVuSansMono-Bold.ttf

Metrics follow PIL's layout (anchor 'la' = left / ascender).
"""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

# (file, variable-font instance name or None)
NS = ("NunitoSans.ttf", b"Bold")
NSI = ("NunitoSans-Italic.ttf", b"Bold Italic")
AR = ("Archivo-Regular.ttf", None)
ARB = ("Archivo-Bold.ttf", None)
WS = ("WorkSans-Regular.ttf", None)
WSB = ("WorkSans-Bold.ttf", None)
DM = ("DejaVuSansMono.ttf", None)
DMB = ("DejaVuSansMono-Bold.ttf", None)

FULL = "".join(chr(c) for c in range(32, 127)) + "µ³°₂"
DIG = "0123456789.-, :"

FONTS = [
    # name, face, size, charset
    ("NSI13", NSI, 13, FULL), ("NS11", NS, 11, FULL), ("NSI21", NSI, 21, DIG),
    ("NS9", NS, 9, FULL), ("NSI24", NSI, 24, DIG), ("NS10", NS, 10, FULL),
    ("NSI12", NSI, 12, FULL), ("NSI38", NSI, 38, DIG), ("NSI10", NSI, 10, FULL),
    ("NSI8", NSI, 8, FULL), ("NSI17", NSI, 17, DIG), ("NS8", NS, 8, FULL),
    ("ARB14", ARB, 14, FULL), ("AR12", AR, 12, FULL), ("AR10", AR, 10, FULL),
    ("ARB22", ARB, 22, DIG), ("AR9", AR, 9, FULL), ("AR8", AR, 8, FULL),
    ("ARB13", ARB, 13, DIG),
    ("WS11", WS, 11, FULL), ("WSB54", WSB, 54, DIG), ("WS9", WS, 9, FULL),
    ("WSB17", WSB, 17, DIG), ("WSB13", WSB, 13, FULL),
    ("DM10", DM, 10, FULL), ("DMB10", DMB, 10, FULL), ("DMB22", DMB, 22, DIG),
]


def has_glyph(font, ch):
    if ch == " ":
        return True
    return bytes(font.getmask(ch)) != bytes(font.getmask("￿"))


def load(font_dir, face, size):
    font = ImageFont.truetype(os.path.join(font_dir, face[0]), size)
    if face[1]:
        font.set_variation_by_name(face[1])
    return font


def gen(name, font, chars):
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in chars:
        if not has_glyph(font, ch):
            continue
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="la")
        w, h = max(x1 - x0, 0), max(y1 - y0, 0)
        if ch == " ":
            w = h = 0
        ofs = len(data) * 2
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="la")
            px = [min(15, (v + 8) // 17) for v in im.getdata()]
            if len(px) % 2:
                px.append(0)
            for i in range(0, len(px), 2):
                data.append(px[i] | (px[i + 1] << 4))
        glyphs.append((ch, w, h, x0, y0, adv, ofs))
    out = [f"pub static {name}: Font = Font {{ ascent: {ascent}, descent: {descent}, glyphs: &["]
    for ch, w, h, x0, y0, adv, ofs in glyphs:
        out.append(f"    Glyph {{ ch: {ch!r}, w: {w}, h: {h}, x: {x0}, y: {y0}, adv: {adv}, ofs: {ofs} }},"
                   .replace("ch: '\\\\'", "ch: '\\\\'").replace("ch: \"'\"", "ch: '\\''"))
    out.append(f"], data: &{name}_DATA }};")
    out.append(f"static {name}_DATA: [u8; {len(data)}] = {list(data)};".replace("[", "[", 1))
    return "\n".join(out), len(data)


def rust_char(ch):
    if ch == "\\":
        return "'\\\\'"
    if ch == "'":
        return "'\\''"
    return f"'{ch}'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--font-dir", required=True)
    args = ap.parse_args()
    parts = ["// @generated by tools/gen_fonts.py — do not edit.",
             "use crate::gfx::{Font, Glyph};", ""]
    total = 0
    for name, face, size, chars in FONTS:
        src, n = gen(name, load(args.font_dir, face, size), chars)
        # fix char literals
        lines = []
        for line in src.split("\n"):
            if line.startswith("    Glyph { ch: "):
                start = line.index("ch: ") + 4
                end = line.index(", w: ")
                lit = line[start:end]
                ch = eval(lit)
                line = line[:start] + rust_char(ch) + line[end:]
            lines.append(line)
        parts.append("\n".join(lines))
        parts.append("")
        total += n
    open(args.out, "w").write("\n".join(parts))
    print(f"{len(FONTS)} fonts, {total} bytes glyph data")


main()
